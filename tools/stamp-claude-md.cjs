#!/usr/bin/env node
//
// stamp-claude-md.cjs — the countable claims in CLAUDE.md, generated instead of typed.
//
//   node tools/stamp-claude-md.cjs            rewrite the marked blocks
//   node tools/stamp-claude-md.cjs --check    report drift, write nothing, exit 1 if stale
//
// Backlog M56/M57. On 18 Aug every counted figure in these files was measured against the
// running system and EVERY ONE WAS WRONG: 21 route files (26), 124 endpoints (147), 14
// panels (17), 18 modules (23), 38 tables (47), "two commits, no remote" (89 commits), 13
// api() wrappers (14), 132 memories (172). The workspace file says of itself "this file
// should stay true for months" and its counts decayed inside a day.
//
// WORSE THAN STALE, THE SCHEMA LIST HAD REGRESSED TO A FAILURE IT DOCUMENTS. It carries the
// warning "the previous version of this block named six modules when thirteen had migrated,
// which is the direction that causes something to be built twice" — and it then listed 16 of
// 23. A session reading it would believe mail, work and exercise did not exist.
//
// EVERY OTHER STATUS SURFACE HERE IS DERIVED. build-dash.sh stamps a STATE marker,
// read-launch.cjs parses LAUNCH.md rather than restating it, panels compute from SQL, and
// launch-tracker.html was DELETED for being hand-ticked — "a progress view that can drift
// from the thing it reports on is worse than none, because it is believed." These files were
// the last hand-typed one, and the most believed, because they load before any work starts.
//
// WHAT THIS DELIBERATELY DOES NOT TOUCH: the prose. The decisions, the reasoning, the traps,
// the "never do these" — that is the entire value of these documents and no tool can write
// it. Only the blocks between the markers are generated. A file a human cannot write into
// would be a worse document than a stale one.
'use strict';
require('./_run-log.cjs').record();

const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { DatabaseSync } = require('node:sqlite');

const ROOT = path.join(__dirname, '..');
const WORKSPACE = path.join(ROOT, '..');
const CHECK = process.argv.includes('--check');

const START = '<!--COUNTS-->';
const END = '<!--END COUNTS-->';

function counts() {
  const routesDir = path.join(ROOT, 'server', 'routes');
  const routeFiles = fs.readdirSync(routesDir).filter((f) => f.endsWith('.js'));
  const endpoints = routeFiles.reduce((n, f) => n
    + (fs.readFileSync(path.join(routesDir, f), 'utf8').match(/router\.(get|post|patch|delete|put)\(/g) || []).length, 0);

  const shell = fs.readFileSync(path.join(ROOT, 'public', 'shell.js'), 'utf8');
  const panels = (shell.match(/\(\) => import/g) || []).length;

  // READ-ONLY, and it matters: this runs from the briefing pass while the server is live,
  // and a stamping tool must never be able to write to the database it is describing.
  const db = new DatabaseSync(path.join(ROOT, 'data', 'dashboard.db'), { readOnly: true });
  const tables = db.prepare('SELECT COUNT(*) AS n FROM sqlite_master WHERE type = ? AND name NOT LIKE ?')
    .get('table', 'sqlite\\_%').n;
  const modules = db.prepare('SELECT module FROM schema_meta ORDER BY module').all().map((r) => r.module);

  // Table names grouped by the module that migrated them, so the schema list cannot drift
  // from schema_meta the way the hand-written one did.
  const allTables = db.prepare('SELECT name FROM sqlite_master WHERE type = ? AND name NOT LIKE ? ORDER BY name')
    .all('table', 'sqlite\\_%').map((r) => r.name);

  const git = (args) => {
    try { return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' }).trim(); }
    catch { return ''; }
  };
  const commits = git(['rev-list', '--count', 'HEAD']) || '?';
  const remote = git(['remote']) ? 'yes' : 'none';

  const memDir = path.join(WORKSPACE, '..', '.claude', 'projects', 'C--Users-jcwhi-Claude-Outputs', 'memory');
  let memories = null;
  try {
    memories = fs.readdirSync(memDir).filter((f) => f.endsWith('.md') && f !== 'MEMORY.md' && !f.startsWith('_')).length;
  } catch { /* the store may not be readable from here; reported as unknown rather than 0 */ }

  const panelDir = path.join(ROOT, 'public', 'panels');
  const ownApi = fs.readdirSync(panelDir).filter((d) => {
    const f = path.join(panelDir, d, `${d}.js`);
    return fs.existsSync(f) && /async function api|const api = /.test(fs.readFileSync(f, 'utf8'));
  }).length;

  return { routeFiles: routeFiles.length, endpoints, panels, tables, modules, allTables, commits, remote, memories, ownApi };
}

function block(c) {
  const stamp = new Date().toISOString().slice(0, 10);
  return [
    START,
    `<!-- Generated by tools/stamp-claude-md.cjs. Do not hand-edit: run the tool. Last: ${stamp} -->`,
    '',
    '| Counted | |',
    '| --- | --- |',
    `| Route files | ${c.routeFiles} |`,
    `| Endpoints | ${c.endpoints} |`,
    `| Panels in the registry | ${c.panels} |`,
    `| Migrated modules | ${c.modules.length} |`,
    `| Tables | ${c.tables} |`,
    `| Commits | ${c.commits}, remote: ${c.remote} |`,
    `| Panels defining their own api() | ${c.ownApi} |`,
    c.memories == null ? '| Memory store | not readable from here |' : `| Memory store | ${c.memories} files |`,
    '',
    `**Migrated modules**, from \`schema_meta\`: ${c.modules.join(' · ')}`,
    '',
    `**Tables**, from \`sqlite_master\`: ${c.allTables.join(' · ')}`,
    '',
    END,
  ].join('\n');
}

function stamp(file, body) {
  if (!fs.existsSync(file)) return { file, state: 'missing' };
  const raw = fs.readFileSync(file, 'utf8');
  const eol = raw.includes('\r\n') ? '\r\n' : '\n';
  const want = body.split('\n').join(eol);
  const i = raw.indexOf(START);
  const j = raw.indexOf(END);
  if (i < 0 || j < 0) return { file, state: 'no markers' };
  const current = raw.slice(i, j + END.length);
  // Ignore the date line when deciding whether anything moved, or every run reports drift.
  const strip = (s) => s.replace(/Last: \d{4}-\d{2}-\d{2}/, '');
  if (strip(current) === strip(want)) return { file, state: 'current' };
  if (CHECK) return { file, state: 'STALE' };
  fs.writeFileSync(file, raw.slice(0, i) + want + raw.slice(j + END.length));
  return { file, state: 'rewritten' };
}

const c = counts();
const body = block(c);
const results = [
  stamp(path.join(ROOT, 'CLAUDE.md'), body),
  stamp(path.join(WORKSPACE, 'CLAUDE.md'), body),
];

results.forEach((r) => console.log(`  ${String(r.state).padEnd(10)} ${path.relative(WORKSPACE, r.file)}`));

const stale = results.filter((r) => r.state === 'STALE');
const missing = results.filter((r) => r.state === 'no markers' || r.state === 'missing');
if (missing.length) {
  console.log(`\n  ${missing.length} file(s) carry no ${START} block, so nothing there is generated`);
  console.log('  and nothing keeps it true. That is reported rather than silently skipped.');
}
if (CHECK && stale.length) {
  console.log(`\n  ${stale.length} file(s) STALE — run without --check to rewrite.`);
  process.exitCode = 1;
}
