#!/usr/bin/env node
//
// install-agents-md.cjs — put the Codex pointer in every repo root, from one source.
//
//   node tools/install-agents-md.cjs          report what is missing or stale
//   node tools/install-agents-md.cjs --apply  write it
//
// WHY A POINTER AND NOT A COPY. Codex loads `AGENTS.md` from the GIT REPO ROOT and does not
// look above it. Measured, not assumed: with the file only at the workspace root, Codex
// answered "NOT IN CONTEXT" having run zero commands; with a file in the repo root it answered
// correctly, also having run zero commands. The workspace root is not a git repo, so it is
// invisible to Codex from inside any project.
//
// That leaves a choice: copy the whole standard into every repo, or point at it. Copying puts
// one rule in ten places, and the first edit to any of them makes the others quietly wrong --
// the same failure the one-owner rule exists to prevent for figures. So each repo gets a short
// pointer, and the pointer is GENERATED so the ten copies cannot drift from each other either.
//
// The pointer carries a few facts rather than being a bare link, because an agent that skips
// the link should still meet the thing most likely to destroy work. Those lines are marked as
// a summary, and the linked file is authoritative.
'use strict';
require('./_run-log.cjs').record();

const fs = require('node:fs');
const path = require('node:path');

const WS = path.join(__dirname, '..', '..');
const APPLY = process.argv.includes('--apply');
const MARKER = '<!-- generated by mission-control/tools/install-agents-md.cjs -- do not hand-edit -->';

const BODY = `# Read the team standard before your first command

${MARKER}

The standard governing every project in this workspace is **\`../AGENTS.md\`**
(\`C:\\Users\\jcwhi\\Claude Outputs\\AGENTS.md\`). **Read it now, in full, before doing anything
else.**

It lives there rather than being copied into each repo because a rule stored twice disagrees
with itself the first time one copy is edited. This file is a pointer, generated from one
source; the linked file is authoritative and this summary is not.

**The four things most likely to cost you if you skip it:**

1. **You share one working tree with several other agents.** \`git pull\` before every commit,
   and \`git commit --only <paths>\` so you do not sweep up another session's staged files.
   Whole-file commits made from a stale copy have silently deleted finished work four times in
   a single day, with no conflict and no warning.
2. **You never contact the owner.** Anything you need from him goes in your handover under
   *Blocked on you*, and reaches him through the manager's one question a day. Only a **P0** --
   active data loss, a live security hole, or a defect invalidating work in flight -- goes
   straight to whoever can stop it.
3. **Write a handover at the end of every session.** A session that files nothing is reported
   by name, and silence looks identical to having nothing to say.
4. **Absence and failure must never look the same.** If a check comes back clean, that is the
   moment to be suspicious rather than relieved -- nobody investigates good news.

<!-- CODEX-READS-THIS: hollowmast-agents-md-v1 -->
`;

// Every directory that is its own git repo. A pointer in a non-repo directory would never be
// read, and one in a repo without agents working in it is harmless.
// A repo can carry a standing brief for one agent alongside the shared standard. Where CODEX.md
// exists, the generated pointer names it — so the brief is found by reading the file Codex
// already loads, rather than by anyone remembering to mention it.
const CODEX_LINE = [
  '',
  '**This repo carries a standing brief: `CODEX.md`.** Read it after `../AGENTS.md` and before',
  'starting work. It says what is yours, what is not, and in what order.',
  '',
].join('\n');

// The expected content depends on whether that brief exists, so "current" is computed per repo
// rather than compared against one constant. Comparing every repo to BODY alone would have
// reported mission-control as permanently stale and rewritten it on every run.
const expectedFor = (repo) => BODY + (fs.existsSync(path.join(WS, repo, 'CODEX.md')) ? CODEX_LINE : '');

const repos = fs.readdirSync(WS, { withFileTypes: true })
  .filter((e) => e.isDirectory() && fs.existsSync(path.join(WS, e.name, '.git')))
  .map((e) => e.name);

if (!repos.length) {
  console.log('\n  FOUND NO REPOSITORIES under the workspace. That is a broken check rather than');
  console.log('  a clean result -- there are known to be several. Investigate before trusting it.\n');
  process.exit(1);
}

console.log('');
let missing = 0; let stale = 0; let ok = 0; let foreign = 0;

for (const r of repos) {
  const p = path.join(WS, r, 'AGENTS.md');
  if (!fs.existsSync(p)) {
    missing += 1;
    console.log(`  MISSING   ${r}`);
    if (APPLY) fs.writeFileSync(p, expectedFor(r));
    continue;
  }
  const cur = fs.readFileSync(p, 'utf8');
  if (cur === expectedFor(r)) { ok += 1; console.log(`  ok        ${r}`); continue; }
  // A file somebody wrote by hand is NOT overwritten silently. Clobbering another agent's
  // instructions to install a pointer would be the rudest possible fix.
  if (!cur.includes(MARKER)) {
    foreign += 1;
    console.log(`  HAND-WRITTEN, left alone   ${r}  -- it does not carry the generated marker`);
    continue;
  }
  stale += 1;
  console.log(`  stale     ${r}`);
  if (APPLY) fs.writeFileSync(p, expectedFor(r));
}

console.log('');
console.log(`  ${repos.length} repo(s): ${ok} current, ${missing} missing, ${stale} stale, ${foreign} hand-written`);
if (!APPLY && (missing || stale)) console.log('  Nothing was written. Re-run with --apply.');
if (APPLY) {
  // Read back rather than trusting the writes.
  const back = repos.filter((r) => {
    const p = path.join(WS, r, 'AGENTS.md');
    return fs.existsSync(p) && fs.readFileSync(p, 'utf8') === expectedFor(r);
  }).length;
  console.log(`  read back: ${back} of ${repos.length - foreign} carry the current pointer`);
}
console.log('');
